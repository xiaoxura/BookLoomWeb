/** 这些特征足够强，不受行长限制，避免长广告行漏网 */
const STRONG_AD_PATTERNS: RegExp[] = [
  /(爱下电子书|ixdzs|苦读书|书友群|下载和分享更多电子书|txt下载|TXT下载)/i,
  /https?:\/\/\S+/i,
  /^[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}$/,
  /^[-—=~*_·]{2,}[^。！？]{0,18}[-—=~*_·]{2,}$/,
  /^[-—=~*_·]{3,}$/,
  /^(?:正文|内容简介|作品简介|本书由|下载地址|最新章节|手机阅读)[:：]?$/,
  /^[『』「」《》〈〉【】（）()[\]]$/,
];

/** 判断一行是否像站点广告 / 水印；体检查残留时复用 */
export function isAdLine(line: string, extra: RegExp[] = []): boolean {
  const t = line.trim();
  if (!t) return false;
  if (extra.some((re) => re.test(t))) return true;
  if (STRONG_AD_PATTERNS.some((re) => re.test(t))) return true;
  if (t.length > 80) return false;
  return AD_PATTERNS.some((re) => re.test(t));
}

const TERMINAL = /[。！？!?…；;」』"'）)】》”’]$/;

function joinText(a: string, b: string): string {
  const last = a.charCodeAt(a.length - 1);
  const first = b.charCodeAt(0);
  const ascii = (c: number) => (c >= 0x30 && c <= 0x39) || (c >= 0x41 && c <= 0x5a) || (c >= 0x61 && c <= 0x7a);
  return ascii(last) && ascii(first) ? `${a} ${b}` : a + b;
}

export interface ParagraphOptions {
  filterAds: boolean;
  /** 用户规则带来的额外丢弃正则，命中即整行删除 */
  drop?: RegExp[];
}

/**
 * 把一段原始行重建成段落。
 * - 大部分行带缩进 → 认为一行就是一段（网文常见）
 * - 否则认为是硬换行 → 按句末标点并段（TXT 导出常见）
 */
export function buildParagraphs(rawLines: string[], opts: ParagraphOptions): string[] {
  const lines = rawLines.map((line) => (opts.filterAds && isAdLine(line, opts.drop) ? '' : line));
  const content = lines.filter((l) => l.trim().length > 0);
  if (content.length === 0) return [];

  const indented = content.filter((l) => /^[\u3000]{1,2}|^\t|^ {2,}/.test(l)).length;
  const useIndent = indented / content.length >= 0.5;

  const out: string[] = [];
  if (useIndent) {
    for (const line of lines) {
      const t = line.trim();
      if (t) out.push(t);
    }
    return out;
  }

  let buf = '';
  for (const line of lines) {
    const t = line.trim();
    if (!t) {
      if (buf) {
        out.push(buf);
        buf = '';
      }
      continue;
    }
    buf = buf ? joinText(buf, t) : t;
    if (TERMINAL.test(t)) {
      out.push(buf);
      buf = '';
    } else if (buf.length >= 20000) {
      // 没有标点的异常长行，按 2 万字切开，避免百万字单段拖垮排版
      out.push(buf.slice(0, 20000));
      buf = buf.slice(20000);
    }
  }
  if (buf) out.push(buf);
  return out;
}
